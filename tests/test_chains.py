def test_reachable_nested_saved_chain_cycle_not_involving_root_is_rejected(tmp_path):
    path_a = tmp_path / "a.aclichain"
    path_b = tmp_path / "b.aclichain"
    path_c = tmp_path / "c.aclichain"
    chain_a = CapabilityChain(id="a", name="A", source_path=path_a, chain_dir=tmp_path)
    chain_b = CapabilityChain(id="b", name="B", source_path=path_b, chain_dir=tmp_path)
    chain_c = CapabilityChain(id="c", name="C", source_path=path_c, chain_dir=tmp_path)
    save_chain(chain_a, path_a)
    save_chain(chain_b, path_b)
    save_chain(chain_c, path_c)

    catalog = {cap.id: cap for cap in list_capabilities(chain_dir=tmp_path)}
    macro_b = next(cap for cap in catalog.values() if cap.defaults.get("chain_id") == "b")
    macro_c = next(cap for cap in catalog.values() if cap.defaults.get("chain_id") == "c")
    chain_a.add_node(macro_b.id, {"path": str(path_b), "chain_id": "b"}, node_id="to-b")
    chain_b.add_node(macro_c.id, {"path": str(path_c), "chain_id": "c"}, node_id="to-c")
    chain_c.add_node(macro_b.id, {"path": str(path_b), "chain_id": "b"}, node_id="back-to-b")
    save_chain(chain_a, path_a)
    save_chain(chain_b, path_b)
    save_chain(chain_c, path_c)

    loaded = load_chain(path_a, capability_catalog=catalog)
    validation = loaded.validate()

    assert validation.valid is False
    assert [error.code for error in validation.errors] == ["recursive_chain"]
    assert str(path_b) in validation.errors[0].message
    assert str(path_c) in validation.errors[0].message
    assert str(path_a) not in validation.errors[0].message
