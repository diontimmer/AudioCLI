@pytest.mark.parametrize(
    ("field_path", "value", "message"),
    [
        (("notes",), ["not", "a", "string"], "field 'notes' must be a string"),
        (("nodes", 0, "enabled"), "false", "field 'enabled' must be a boolean"),
        (("nodes", 0, "params"), ["not", "an", "object"], "params must be an object"),
    ],
)
def test_native_chain_load_rejects_malformed_core_field_types(tmp_path, field_path, value, message):
    payload = {
        "schema_version": 1,
        "kind": "audiocli.saved_chain",
        "id": "strict-schema",
        "name": "Strict Schema",
        "nodes": [
            {
                "id": "gain",
                "node_type": "capability",
                "capability_id": "builtin.filter.gain",
                "enabled": True,
                "params": {"db": 1},
            }
        ],
    }
    target = payload
    for key in field_path[:-1]:
        target = target[key]
    target[field_path[-1]] = value
    path = tmp_path / f"bad-core-{len(field_path)}.aclichain"
    path.write_text(json.dumps(payload))

    with pytest.raises(ChainFormatError) as error:
        load_chain(path)

    assert error.value.code == "schema_error"
    assert message in str(error.value)


def test_invalid_native_chain_kind_is_excluded_from_macro_discovery(tmp_path):
    valid = CapabilityChain(id="valid", name="Valid")
    invalid = CapabilityChain(id="invalid", name="Invalid")
    valid_path = save_chain(valid, tmp_path / "valid.aclichain")
    invalid_path = save_chain(invalid, tmp_path / "invalid.aclichain")
    invalid_payload = json.loads(invalid_path.read_text())
    invalid_payload["kind"] = "not.audiocli.saved_chain"
    invalid_path.write_text(json.dumps(invalid_payload))

    capabilities = list_capabilities(chain_dir=tmp_path)
    macro_chain_ids = {
        capability.defaults.get("chain_id")
        for capability in capabilities
        if capability.type == "saved_chain_macro"
    }

    assert valid_path.exists()
    assert "valid" in macro_chain_ids
    assert "invalid" not in macro_chain_ids


def test_direct_saved_chain_recursion_is_rejected(tmp_path):
    from audiocli.capabilities import list_capabilities

    path = tmp_path / "self.aclichain"
    chain = CapabilityChain(id="self", name="Self", source_path=path, chain_dir=tmp_path)
    save_chain(chain, path)
    catalog = {cap.id: cap for cap in list_capabilities(chain_dir=tmp_path)}
    macro = next(cap for cap in catalog.values() if cap.type == "saved_chain_macro")
    chain.add_node(macro.id, {"path": str(path), "chain_id": "self"}, node_id="macro")
    save_chain(chain, path)

    loaded = load_chain(path, capability_catalog=catalog)
    validation = loaded.validate()

    assert validation.valid is False
    assert validation.errors[0].code == "recursive_chain"
    assert "Recursive saved-chain reference rejected" in validation.errors[0].message


def test_indirect_saved_chain_recursion_is_rejected(tmp_path):
    from audiocli.capabilities import list_capabilities

    path_a = tmp_path / "a.aclichain"
    path_b = tmp_path / "b.aclichain"
    chain_a = CapabilityChain(id="a", name="A", source_path=path_a, chain_dir=tmp_path)
    chain_b = CapabilityChain(id="b", name="B", source_path=path_b, chain_dir=tmp_path)
