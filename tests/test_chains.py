def test_chain_editing_operations_keep_stable_order_and_serializable_state():
    sys.modules.pop("audiocli.cli", None)
    chain = CapabilityChain(id="chain-1", name="Mastering")

    chain.add_node("builtin.filter.gain", {"db": "-3"}, node_id="gain-1")
    chain.add_node("builtin.filter.highpass", {"hz": 120}, node_id="hp-1")
    chain.move_node("hp-1", 0)
    chain.duplicate_node("gain-1", node_id="gain-2", index=1)
    chain.update_node_params("gain-2", {"db": 6})
    chain.set_node_enabled("gain-1", False)

    assert isinstance(chain, ChainModel)
    assert [node.id for node in chain.nodes] == ["hp-1", "gain-2", "gain-1"]
    assert chain.nodes[2].enabled is False
    assert chain.nodes[1].params == {"db": 6}
    assert "audiocli.cli" not in sys.modules

    view_model = chain.to_view_model()
    assert view_model["id"] == "chain-1"
    assert [node["position"] for node in view_model["nodes"]] == [0, 1, 2]
    assert [node["capability_id"] for node in view_model["nodes"]] == [
        "builtin.filter.highpass",
        "builtin.filter.gain",
        "builtin.filter.gain",
    ]
    assert view_model["nodes"][2]["enabled"] is False
    assert view_model["nodes"][1]["params"] == {"db": 6}
    assert view_model["nodes"][1]["capability"]["display_name"] == "Gain"
    assert view_model["validation_state"]["valid"] is True

    serialized = chain.to_dict()
    assert serialized == {
        "version": 1,
        "id": "chain-1",
        "name": "Mastering",
        "nodes": [
            {
                "id": "hp-1",
                "capability_id": "builtin.filter.highpass",
                "enabled": True,
                "params": {"hz": 120},
            },
            {
                "id": "gain-2",
                "capability_id": "builtin.filter.gain",
                "enabled": True,
                "params": {"db": 6},
            },
            {
                "id": "gain-1",
                "capability_id": "builtin.filter.gain",
                "enabled": False,
                "params": {"db": "-3"},
            },
        ],
    }
    json.dumps(serialized, allow_nan=False)

    removed = chain.delete_node("gain-2")
    assert removed.id == "gain-2"
    assert [node.id for node in chain.nodes] == ["hp-1", "gain-1"]


def test_chain_rejects_duplicate_node_ids_in_editing_operations():
    chain = CapabilityChain(id="chain-duplicates")
    first = chain.add_node("builtin.filter.gain", {"db": 1}, node_id="gain")

    with pytest.raises(ValueError, match="Duplicate chain node id 'gain'"):
        chain.add_node("builtin.filter.highpass", {"hz": 120}, node_id="gain")

    assert chain.nodes == [first]

    with pytest.raises(ValueError, match="Duplicate chain node id 'gain'"):
        chain.duplicate_node("gain", node_id="gain")

    with pytest.raises(ValueError, match="Duplicate chain node id 'gain'"):
        chain.duplicate_node("gain", new_node_id="gain")

    second = chain.add_node("builtin.filter.highpass", {"hz": 120}, node_id="highpass")
    with pytest.raises(ValueError, match="Duplicate chain node id 'highpass'"):
        chain.duplicate_node("gain", new_node_id="highpass")

    autogenerated = chain.duplicate_node("gain")

    assert [node.id for node in chain.nodes[:2]] == ["gain", autogenerated.id]
    assert autogenerated.id not in {first.id, second.id}


def test_disabled_nodes_remain_in_editor_but_are_skipped_by_validation_and_plan():
    chain = CapabilityChain(id="chain-disabled")
    chain.add_node("builtin.filter.gain", {"db": 2.5}, node_id="gain")
    chain.add_node(
        "missing.capability", {"bad": object()}, node_id="disabled-unknown", enabled=False
    )
    chain.add_node(
        "builtin.filter.highpass", {"hz": "not-a-number"}, node_id="disabled-invalid", enabled=False
    )

    validation = chain.validate()
    plan = chain.to_execution_plan()
    view_model = chain.to_view_model()

    assert validation.valid is True
    assert validation.errors == []
    assert [step.node_id for step in plan.steps] == ["gain"]
    assert view_model["node_count"] == 3
    assert view_model["enabled_node_count"] == 1
    assert [node["id"] for node in view_model["nodes"]] == [
        "gain",
        "disabled-unknown",
        "disabled-invalid",
    ]
    assert view_model["nodes"][1]["enabled"] is False
    assert view_model["nodes"][1]["capability"] is None
    assert view_model["nodes"][1]["validation_state"]["skipped"] is True


def test_chain_validation_reports_unknown_capability_bad_params_and_no_enabled_nodes():
    chain = CapabilityChain(id="bad-chain")
    chain.add_node("builtin.filter.gain", {}, node_id="gain-missing-db")
    chain.add_node("does.not.exist", {}, node_id="unknown")

    validation = chain.validate()

    assert validation.valid is False
    errors = {(error.node_id, error.code, error.parameter) for error in validation.errors}
    assert ("gain-missing-db", "missing_required", "db") in errors
    assert ("unknown", "unknown_capability", "") in errors
    assert validation.to_view_model()["valid"] is False

    disabled_only = CapabilityChain(id="disabled-only")
    disabled_only.add_node("builtin.filter.gain", {"db": 1}, node_id="gain", enabled=False)

    disabled_validation = disabled_only.validate()

    assert disabled_validation.valid is False
    assert [error.code for error in disabled_validation.errors] == ["no_enabled_nodes"]


def test_compatibility_validation_catches_incompatible_enabled_sequence_before_execution():
    audio_filter = get_capability("builtin.filter.highpass")
    metadata_shape = IOShape(
        kind="metadata",
        media_type="application/json",
        cardinality="single",
        description="Analysis metadata, not audio.",
    )
    analysis_capability = replace(
        audio_filter,
        id="test.analysis.metadata",
        type="analysis",
        display_name="Metadata Analysis",
        output_shape=metadata_shape,
        operation_name="metadata-analysis",
    )
    chain = CapabilityChain(
        id="incompatible",
        capability_catalog={
            analysis_capability.id: analysis_capability,
            audio_filter.id: audio_filter,
        },
    )
    chain.add_node(analysis_capability.id, node_id="analysis")
    chain.add_node(audio_filter.id, node_id="filter")

    validation = chain.validate()

    assert validation.valid is False
    assert len(validation.errors) == 1
    error = validation.errors[0]
    assert error.code == "incompatible_shapes"
    assert error.source_node_id == "analysis"
    assert error.node_id == "filter"
    assert "metadata" in error.message
    assert "audio_buffer" in error.message

    chain.set_node_enabled("analysis", False)
    assert [node.id for node in chain.nodes] == ["analysis", "filter"]
    assert chain.validate().valid is True
    assert [step.node_id for step in chain.to_execution_plan().steps] == ["filter"]


def test_chain_validation_allows_chunk_collection_into_filter_explicitly():
    chain = CapabilityChain(id="chunk-map")
    chain.add_node(
        "builtin.multi_output.chunk",
        {"seconds": 10.0, "pad": False},
        node_id="chunk",
    )
    chain.add_node("builtin.filter.gain", {"db": 0.0}, node_id="gain")

    validation = chain.validate()
    plan = chain.to_execution_plan()

    assert validation.valid is True
    assert validation.errors == []
    assert len(validation.collection_mappings) == 1
    mapping = validation.collection_mappings[0]
    assert mapping.source_node_id == "chunk"
    assert mapping.node_id == "gain"
    assert mapping.source_cardinality == "many"
    assert mapping.input_cardinality == "single"
    assert mapping.behavior == "map_each_file"
    assert validation.to_view_model()["collection_mappings"][0]["behavior"] == "map_each_file"
    assert [step.operation_name for step in plan.steps] == ["chunk", "gain"]


